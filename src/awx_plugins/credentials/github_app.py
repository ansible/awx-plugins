class MaybeBaseURLKwarg(TypedDict, total=False):
    """Schema for optional PyGitHub ``base_url`` keyword arg."""
    base_url: str


def extract_github_app_install_token(
    *,
    github_api_url: str,
    app_id: str,
    private_rsa_key: str,
    install_id: str,
    **_discarded_kwargs: dict[object, object],
) -> str:
    """Generate a GitHub authentication token from GitHub App Installation
    credentials.

    :param github_api_url: The GitHub instance API endpoint URL.
    :param app_id: The GitHub App ID.
    :param private_rsa_key: The private key associated with the GitHub
        App.
    :param install_id: The GitHub App Installation ID.
    :returns: A GitHub access token for a GitHub App Installation.
    :raises ValueError: If any required parameters are invalid.
    """
    if not app_id.isdigit():
        raise ValueError(
            f'Expected GitHub App ID to be an integer but got {app_id !r}',
        )

    if not install_id.isdigit():
        raise ValueError(
            'Expected GitHub App Installation ID to be an integer'
            f' but got {install_id !r}',
        )

    auth = Auth.AppAuth(
        app_id=int(app_id),
        private_key=private_rsa_key,
    ).get_installation_auth(installation_id=int(install_id))

    extra_gh_args: MaybeBaseURLKwarg = {
        'base_url': github_api_url,
    } if github_api_url else {}
    Github(  # Generate a GitHub App authentication token
        auth=auth,
        **extra_gh_args,
    )

    return auth.token


github_app_lookup = CredentialPlugin(  # type: ignore[misc]  # untyped tuple
    'GitHub App Installation Access Token Lookup',
    inputs=github_app_inputs,
    backend=extract_github_app_install_token,
)
